// Regenerates lib/src/native/opus_bindings.dart from the vendored headers.
//
//   dart run tool/ffigen.dart
//
// CI runs this and fails if the committed bindings differ.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// The ABI contract: the functions the codec classes bind. Anything else in
/// the headers (multistream, projection, repacketizer, custom modes) stays
/// out of the bindings until it is designed in deliberately.
const _functions = {
  'opus_get_version_string',
  'opus_strerror',
  'opus_encoder_get_size',
  'opus_encoder_create',
  'opus_encoder_init',
  'opus_encode',
  'opus_encode_float',
  'opus_encoder_destroy',
  'opus_codec_encoder_ctl_int',
  'opus_decoder_get_size',
  'opus_decoder_create',
  'opus_decoder_init',
  'opus_decode',
  'opus_decode_float',
  'opus_decoder_destroy',
  'opus_packet_parse',
  'opus_packet_get_bandwidth',
  'opus_packet_get_samples_per_frame',
  'opus_packet_get_nb_channels',
  'opus_packet_get_nb_frames',
  'opus_packet_get_nb_samples',
  'opus_decoder_get_nb_samples',
  'opus_pcm_soft_clip',
};

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final include = root.resolve('native/vendor/opus/include/');
  final shim = root.resolve('native/shim/');

  await FfiGenerator(
    input: Input(
      entryPoints: [
        include.resolve('opus.h'),
        shim.resolve('opus_codec_shim.h'),
      ],
      include: (header) =>
          header.path.startsWith(include.path) ||
          header.path.startsWith(shim.path),
      compilerOptions: ['-I${include.toFilePath()}'],
    ),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/native/opus_bindings.dart')),
      // Must match the asset the build hook publishes (hook/build.dart).
      style: const NativeExternalBindings(
        assetId: 'package:opus_codec_dart/src/native/opus_bindings.dart',
      ),
      preamble:
          '// Generated by tool/ffigen.dart. Do not edit.\n'
          '// ignore_for_file: type=lint',
    ),
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = _functions.contains(node.name),
        macroConstant: (node) => node.isIncluded = false,
        enumClass: (node) => node.isIncluded = false,
        unnamedEnumConstant: (node) => node.isIncluded = false,
        global: (node) => node.isIncluded = false,
      ),
    ],
  ).generate(libclangDylib: _libclang());
}

/// LIBCLANG_PATH overrides ffigen's default search, which can pick up a
/// libclang built for the wrong architecture.
Uri? _libclang() {
  final path = Platform.environment['LIBCLANG_PATH'];
  return path == null ? null : Uri.file(path);
}
